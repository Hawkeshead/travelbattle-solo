# ---- batch 2 ----
def roadgrid(*paths):
    g = [['.'] * 20 for _ in range(10)]
    for path in paths:
        for (x0, y0), (x1, y1) in zip(path, path[1:]):
            if x0 == x1:
                for y in range(min(y0, y1), max(y0, y1) + 1): g[y][x0] = '='
            else:
                for x in range(min(x0, x1), max(x0, x1) + 1): g[y0][x] = '='
    return [''.join(r) for r in g]

